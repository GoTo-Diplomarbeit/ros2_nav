#!/bin/bash
# Build a Python virtualenv that PyCharm can use for the Go2 project with FULL
# autocomplete, error checking, and working breakpoints.
#
# Why this is needed at all:
#   ROS 2 does not install rclpy into a normal site-packages. It lives in
#   /opt/ros/jazzy/lib/python3.12/site-packages and is only reachable because
#   setup.bash exports PYTHONPATH. PyCharm does not run setup.bash, so it sees
#   nothing. On top of that, ROS 2 python packages are partly native C++ that
#   needs LD_LIBRARY_PATH, or the import dies with
#   "libackermann_msgs__rosidl_generator_py.so: cannot open shared object file"
#   - which PyCharm reports as "failed to run generator3/__main__.py", exit 139.
#
# What this produces:
#   ~/venvs/go2/bin/.python-base   <- symlink to the real interpreter. Kept under
#                                     its own name on purpose; see the note on
#                                     the venv layout below.
#   ~/venvs/go2/bin/python         <- a wrapper carrying the ROS 2 environment.
#   ~/venvs/go2/bin/python3        <- the same wrapper.
#   ~/venvs/go2/bin/python3.12     <- the same wrapper.
#   ~/venvs/go2/bin/python-ros     <- the same wrapper under its old name, for
#                                     the command line and anything already
#                                     pointing at it.
#
# The venv layout this has to work around (POSIX, see Lib/venv/__init__.py):
#   python -> /usr/bin/python3.12     absolute
#   python3 -> python                 RELATIVE
#   python3.12 -> python              RELATIVE
# So the real interpreter must NOT live behind any of those names: replacing
# bin/python with a script makes python3.12 resolve to that script, and a
# wrapper that execs python3.12 would exec itself forever. Each recursion level
# re-appends PYTHONPATH, so it dies with the thoroughly misleading
# "Argument list too long" instead of a useful error.
#
# Re-run this script after `colcon build` in ~/go2_ws, because rebuilding
# regenerates the install/ overlay and the paths can change.

set -e

# Do not run under sudo: $HOME becomes /root, so the workspace overlay is looked
# for in the wrong place, and the venv would end up owned by root - which then
# breaks PyCharm, because the IDE runs as your normal user. Nothing here needs
# root, so refuse instead of half-doing it as the wrong user.
if [ -n "${SUDO_USER:-}" ] || [ "$(id -u)" -eq 0 ]; then
  echo "ERROR: run this script as your normal user, not with sudo." >&2
  echo "       HOME is currently $HOME; the venv must live in your own home." >&2
  exit 1
fi

VENV_DIR="$HOME/venvs/go2"
BIN="$VENV_DIR/bin"
ROS_SETUP="/opt/ros/jazzy/setup.bash"
WS_SETUP="$HOME/go2_ws/install/setup.bash"

echo "==> Reading ROS 2 environment"
# shellcheck disable=SC1090
source "$ROS_SETUP"
# shellcheck disable=SC1090
source "$WS_SETUP"

if [ -z "${PYTHONPATH:-}" ]; then
  echo "ERROR: PYTHONPATH is empty after sourcing. Is the Go2 workspace built?" >&2
  exit 1
fi

echo "==> Repairing interpreter links in $BIN"
# A bad earlier run can leave python -> python (self-referential) or a dangling
# python3 -> python. 'python3 -m venv' can never heal that: for each of these
# names it only acts when the path does not exist, and a broken symlink still
# exists as a link. Remove broken links so venv recreates them properly.
for name in python python3 python3.12; do
  link="$BIN/$name"
  if [ -L "$link" ] && [ ! -e "$link" ]; then
    echo "    removing broken link $link"
    rm -f "$link"
  elif [ -f "$link" ] && grep -q 'Generated by setup-venv.sh' "$link" 2>/dev/null; then
    # Our own wrapper from a previous run. venv links bin/python3
    # unconditionally, so leaving it in place makes venv log "Unable to
    # symlink" and copy the whole system interpreter over it every run.
    echo "    removing previous wrapper $link"
    rm -f "$link"
  fi
done

echo "==> Creating venv at $VENV_DIR"
# --system-site-packages is kept so ordinary apt-installed python3 libraries
# (numpy etc.) are visible too. It does NOT pick up ROS on its own.
# Re-running is safe: venv leaves alone any of these names that already exists.
python3 -m venv --system-site-packages "$VENV_DIR"

echo "==> Locating the interpreter this venv was built from"
# pyvenv.cfg is written by venv itself and records the base interpreter, so it
# stays correct no matter what state bin/ is in.
BASE="$(sed -n 's/^executable = //p' "$VENV_DIR/pyvenv.cfg" 2>/dev/null | head -1)"
if [ ! -x "$BASE" ]; then
  BASE="$(readlink -f "$(command -v python3 2>/dev/null || echo /usr/bin/python3)")"
fi
if [ ! -x "$BASE" ]; then
  echo "ERROR: cannot find the interpreter this venv was built from." >&2
  echo "       Delete $VENV_DIR and re-run this script." >&2
  exit 1
fi

echo "==> Keeping the real interpreter at $BIN/.python-base -> $BASE"
rm -f "$BIN/.python-base"
ln -s "$BASE" "$BIN/.python-base"

SITE_PACKAGES="$("$BIN/python" -c 'import site; print(site.getsitepackages()[0])')"

echo "==> Writing $SITE_PACKAGES/ros2.pth"
# Static, not runtime-generated, so importing works even with a bare env.
printf '%s\n' "$PYTHONPATH" | tr ':' '\n' > "$SITE_PACKAGES/ros2.pth"

echo "==> Blocking the broken system 'sip' module"
# /usr/lib/python3/dist-packages/sip.cpython-312-*.so is python3-sip 4.19.25, a
# PyQt4-era module that imports fine on Python 3.12 but SEGFAULTS during
# interpreter shutdown. PyCharm's skeleton generator imports sip on purpose
# (generator3/constants.py, to detect Qt wrapper classes), so every generation
# run finished all its work and then died with
#   failed to run generator3/__main__.py ... exit code 139   (empty stderr)
# and PyCharm threw the skeletons away, leaving binary modules unresolved.
# A .py stub in this venv's site-packages shadows the .so, because an earlier
# sys.path entry wins over a later one regardless of file type. Do NOT
# 'apt remove python3-sip' - that also removes python3-matplotlib.
cat > "$SITE_PACKAGES/sip.py" <<'EOF'
# Installed by setup-venv.sh.
#
# python3-sip 4.19.25 (PyQt4 era) is importable under Python 3.12 but segfaults
# the interpreter at shutdown. PyCharm's generator3/constants.py imports sip to
# detect Qt wrapper classes, so every skeleton generation ended in exit code 139
# after doing all its work. Shadowing it here makes the import fail cleanly and
# generator3 takes its normal "no sip available" path. Nothing here uses Qt.
raise ImportError(
    "sip is disabled for this venv: python3-sip 4.19.25 segfaults at "
    "interpreter exit on Python 3.12. See unitree_movement/README.md."
)
EOF

sip_rc=0
"$VENV_DIR/bin/python" -c 'import sip' >/dev/null 2>&1 || sip_rc=$?
if [ "$sip_rc" -eq 0 ]; then
  echo "  WARNING: sip is still importable - the stub is not shadowing it." >&2
elif [ "$sip_rc" -eq 139 ]; then
  echo "  ERROR: importing sip still segfaults - the stub is not being used." >&2
fi

echo "==> Writing $VENV_DIR/etc/ros.env"
mkdir -p "$VENV_DIR/etc"
{
  echo "PYTHONPATH=$PYTHONPATH"
  echo "LD_LIBRARY_PATH=$LD_LIBRARY_PATH"
  echo "AMENT_PREFIX_PATH=${AMENT_PREFIX_PATH:-}"
} > "$VENV_DIR/etc/ros.env"

echo "==> Installing the ROS 2 wrapper as $BIN/python"
write_wrapper() {
  # Remove first. These names are symlinks (python -> /usr/bin/python3.12, and
  # python3 / python3.12 -> python), and 'cat > symlink' follows the link: you
  # either get "Permission denied" writing the root-owned system interpreter,
  # or you write into something that is itself a wrapper.
  rm -f "$1"
  cat > "$1" <<'EOF'
#!/bin/bash
# Generated by setup-venv.sh - re-run that script after 'colcon build'.
#
# PyCharm never sources ROS 2's setup.bash, so this wrapper carries the
# environment itself and then hands off to the interpreter kept at
# .python-base in this same directory.
#
# Shell builtins only: PyCharm launches interpreters with a minimal
# environment, so no external command (dirname, readlink) and no PATH may be
# assumed.
case "$0" in
  */*) HERE="${0%/*}" ;;
  *)   HERE="." ;;
esac
HERE="$(cd "$HERE" && pwd)"
VENV="${HERE%/*}"
BASE="$HERE/.python-base"

# Guard: if .python-base ever resolves back to a wrapper, exec'ing it would
# recurse, and every level re-appends PYTHONPATH until execve fails with a
# bogus "Argument list too long". Say what is actually wrong instead.
if [ ! -x "$BASE" ]; then
  echo "venv wrapper: $BASE is missing - re-run setup-venv.sh" >&2
  exit 127
fi
read -r -n 2 _MAGIC < "$BASE" 2>/dev/null || true
if [ "$_MAGIC" = "#!" ]; then
  echo "venv wrapper: $BASE is a shell script, not an interpreter." >&2
  echo "              Re-run setup-venv.sh from a WSL terminal to repair it." >&2
  exit 127
fi

_OLD_PYTHONPATH="$PYTHONPATH"
_OLD_LD_LIBRARY_PATH="$LD_LIBRARY_PATH"
_OLD_AMENT_PREFIX_PATH="$AMENT_PREFIX_PATH"

if [ -r "$VENV/etc/ros.env" ]; then
  . "$VENV/etc/ros.env"
else
  echo "venv wrapper: $VENV/etc/ros.env is missing - re-run setup-venv.sh" >&2
fi

export PYTHONPATH="$PYTHONPATH${_OLD_PYTHONPATH:+:$_OLD_PYTHONPATH}"
export LD_LIBRARY_PATH="$LD_LIBRARY_PATH${_OLD_LD_LIBRARY_PATH:+:$_OLD_LD_LIBRARY_PATH}"
export AMENT_PREFIX_PATH="$AMENT_PREFIX_PATH${_OLD_AMENT_PREFIX_PATH:+:$_OLD_AMENT_PREFIX_PATH}"

exec "$BASE" "$@"
EOF
  chmod +x "$1"
}

write_wrapper "$BIN/python"
write_wrapper "$BIN/python3"
write_wrapper "$BIN/python3.12"
write_wrapper "$BIN/python-ros"

echo "==> Verifying with a completely clean environment"
if ! env -i HOME="$HOME" "$BIN/python" - <<'PY'
import sys
import rclpy
import action_msgs.msg
import geometry_msgs.msg
import nav_msgs.msg
import sensor_msgs.msg
from rclpy.node import Node

assert sys.prefix != sys.base_prefix, (
    "the venv is not active (sys.prefix == sys.base_prefix == %r)"
    % (sys.prefix,))

print("  interpreter    :", sys.executable)
print("  venv prefix    :", sys.prefix)
print("  rclpy          :", rclpy.__file__)
print("  Twist          :", geometry_msgs.msg.Twist)
print("  Odometry       :", nav_msgs.msg.Odometry)
print("  Node           :", Node)
PY
then
  echo "ERROR: $BIN/python does not work; restoring plain interpreter links." >&2
  # Point the three names straight at the base interpreter, so the venv is
  # usable even though it carries no ROS 2 environment. Never link them to each
  # other: a self-referential python -> python is exactly how this got broken.
  for name in python python3 python3.12; do
    rm -f "$BIN/$name"
    ln -s "$BASE" "$BIN/$name"
  done
  echo "       PyCharm will keep showing the rosidl / LD_LIBRARY_PATH error" >&2
  echo "       until this is fixed. Please report the output above." >&2
  exit 1
fi

echo
echo "Done. In PyCharm point at the venv DIRECTORY:"
echo "  Settings > Project > Python Interpreter > Add Interpreter"
echo "            > On WSL > Ubuntu-24.04 > existing environment"
echo "            > $VENV_DIR"
echo
echo "Not at a file inside bin/: that page always resolves '<what you enter>"
echo "/bin/python', so $BIN/python-ros becomes '$BIN/python-ros/bin/python'"
echo "and fails with 'Not a directory' (exit 126)."
